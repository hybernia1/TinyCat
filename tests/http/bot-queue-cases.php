<?php
declare(strict_types=1);
$queueDb = new PDO('sqlite:' . $databasePath);
$queueDb->exec("INSERT INTO users (id,username,role,status) VALUES (901,'Queue fixture','bot','active')");
$queueDb->exec("INSERT INTO content (id,author_id,body,published_at) VALUES (9001,901,'Queue test','2099-01-01 12:00:00'), (9002,2,'Human future','2099-01-01 12:00:00')");
[$status] = $request('GET', '/api/bots/queue');
$assert($status === 401, 'The publication queue requires authentication.');
[$status] = $request('GET', '/api/bots/queue', null, 'user');
$assert($status === 403, 'The publication queue is administrator-only.');
[$status, $queued] = $request('GET', '/api/bots/queue?bot=901&per_page=10&sort=published_at&direction=asc', null, 'admin');
$assert($status === 200 && count($queued['data']['items']) === 1 && $queued['meta']['pagination']['total'] === 1, 'The queue uses the canonical list envelope with filters.');
$publishPath = '/api/bots/queue/9001/publication?bot=901&per_page=10';
[$status] = $request('POST', $publishPath, [], 'user', $csrf);
$assert($status === 403, 'Publishing requires administrator privileges.');
[$status] = $request('POST', $publishPath, [], 'admin');
$assert($status === 403, 'Publishing requires CSRF protection.');
$queueDb->exec("UPDATE users SET status='ban' WHERE id=901");
[$status, $blocked] = $request('POST', $publishPath, [], 'admin', $csrf);
$assert($status === 409 && $blocked['code'] === 'bot_inactive', 'An inactive bot cannot publish through a stale or forged action.');
$assert($queueDb->query('SELECT published_at FROM content WHERE id=9001')->fetchColumn() === '2099-01-01 12:00:00', 'Rejected publication keeps the scheduled time.');
$queueDb->exec("UPDATE users SET status='active' WHERE id=901");
[$status, $published] = $request('POST', $publishPath, [], 'admin', $csrf);
$assert($status === 201 && $published['code'] === 'bot_queue_published' && $published['data']['items'] === [] && $published['meta']['pagination']['total'] === 0, 'Publishing returns the refreshed filtered queue.');
$publishedAt = $queueDb->query('SELECT published_at FROM content WHERE id=9001')->fetchColumn();
$assert($publishedAt < '2099-01-01', 'The post becomes eligible for the public timeline.');
[$status] = $request('POST', $publishPath, [], 'admin', $csrf);
$assert($status === 201 && $queueDb->query('SELECT published_at FROM content WHERE id=9001')->fetchColumn() === $publishedAt, 'Publication retries leave the original publication time intact.');
[$status] = $request('POST', '/api/bots/queue/9002/publication', [], 'admin', $csrf);
$assert($status === 404, 'The bot publication action cannot publish human posts.');
[$status] = $request('POST', '/api/bots/queue/999999/publication', [], 'admin', $csrf);
$assert($status === 404, 'Missing queue entries return the shared not-found error.');
$queueDb->exec('DELETE FROM content WHERE id IN (9001,9002)');
$queueDb->exec('DELETE FROM users WHERE id=901');
$queueDb = null;
